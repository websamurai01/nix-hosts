#!/usr/bin/env bash

# 1. Переводим главный монитор в разрешение 4:3
# Если 1440x1080 не сработает, поменяй здесь на 1280x960
hyprctl keyword monitor HDMI-A-1, 1440x1080, 0x0, 1

# 2. Запускаем CS2
"$@"

# 3. Когда CS2 закрывается — возвращаем родное 2K разрешение и 180 Гц
hyprctl keyword monitor HDMI-A-1, 2560x1440@180, 0x0, 1
